"""Очистка разметки Obsidian перед сборкой PDF/HTML.

В биографиях и расшифровках люди упомянуты ссылками на карточки: [[Иван Ясенев|@I25@]].
В книге такие ссылки не нужны — остаётся только видимый текст (@I25@ или имя).
"""
import re


def strip_wikilinks(text):
    text = re.sub(r"!\[\[[^\]]+\]\]", "", text)                       # встраивания Obsidian
    text = re.sub(r"\[\[[^\]|]+\\?\|([^\]]+)\]\]", r"\1", text)         # [[цель|текст]] → текст
    return re.sub(r"\[\[([^\]#]+?)(?:#[^\]]*)?\]\]", lambda m: m.group(1).rsplit("/", 1)[-1].removesuffix(".md"), text)
