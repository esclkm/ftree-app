_CYR = re.compile(r"^[а-яё]+$")


@lru_cache(maxsize=1)
def _rows() -> dict[str, frozenset[str]]:
    """Имя → все равные ему (ряды с общим именем слиты)."""
    groups: list[set[str]] = []
    for row in GIVEN:
        row_set = {x for x in row if _CYR.match(x)}
        joined = [g for g in groups if g & row_set]
        for g in joined:
            row_set |= g
            groups.remove(g)
        groups.append(row_set)
    return {n: frozenset(g) for g in groups for n in g}


def forms(given: str) -> list[str]:
    """Все известные формы имени, строчными, кириллицей; неизвестное имя — само по себе."""
    g = given.strip().lower()
    return sorted(_rows().get(g, {g}), key=lambda x: (x != g, x))


def patronymic(father: str) -> str:
    """Как крестьянина записывали по отцу (ответ строчными): прокоп → прокопов, сергей → сергеев,
    василий → василиев, никита → никитин, илья → ильин."""
    f = father.strip().lower()
    if f.endswith("ий"):
        return f[:-2] + "иев"
    if f.endswith(("ей", "ай", "уй")):
        return f[:-1] + "ев"
    if f.endswith(("ия", "ья")):
        return f[:-2] + "ьин" if f[-3] not in "аеиоуыэюя" else ""     # илья → ильин; исаия — только «исаев» (от исай)
    if f.endswith(("а", "я")):
        return f[:-1] + "ин"
    if f.endswith("ь"):
        return f[:-1] + "ев"
    return f + "ов"


def patronymic_surnames(father: str) -> list[str]:
    """«Фамилия по отцу» для всех форм имени отца, без повторов: Василий → василиев, васильев."""
    out = []
    for f in forms(father):
        p = patronymic(f)
        out += [p, p.replace("иев", "ьев")] if p.endswith("иев") else [p] if p else []
    return list(dict.fromkeys(out))


@lru_cache(maxsize=1)
def manual() -> dict[str, dict]:
    """Ручные написания по номеру карточки: {cr_id: {"given": [...], "written": ["Агата Прокопова"]}}.
    Пополняется находками, где имя в книге не совпало с домашним."""
    if not MANUAL.exists():
        return {}
    return {k: v for k, v in tomllib.loads(MANUAL.read_text(encoding="utf-8")).items() if isinstance(v, dict)}
