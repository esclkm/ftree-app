// Строка источника под фото — короче: голые адреса ссылкой с именем сайта.
/** Голый адрес в подписи → ссылка с именем сайта: «https://goskatalog.ru/portal/#/…» → [goskatalog.ru](…) — строка источника
 *  не занимает пол-карточки. Адреса внутри готовых ссылок [текст](адрес) не трогаем. */
export const shortUrls = (s = '') => s.replace(/(?<!\]\()(?<!\[)\bhttps?:\/\/[^\s)\]]+/g, url => {
  const host = url.replace(/^https?:\/\/(www\.)?/, '').split(/[/?#]/)[0]
  return `[${host}](${url})`
})
