// Скруглённые углы линий «родители → ребёнок» (tree/links.ts, roundedPath)
import {describe, expect, it} from 'vitest'
import {roundedPath} from '../src/tree/links'

// ломаная, как у библиотеки: ребёнок (0,100) → вниз до 50 → вбок до x=40 → к родителям (40,0)
const pts: [number, number][] = [[0, 100], [0, 50], [0, 50], [40, 50], [40, 50], [40, 0]]

describe('скруглённые углы линий', () => {
  it('два угла с радиусом 6', () => expect(roundedPath(pts, 6)).toBe('M0,100L0,56Q0,50 6,50L34,50Q40,50 40,44L40,0'))
  it('узкий шаг — радиус не больше половины', () => expect(roundedPath([[0, 100], [0, 50], [0, 50], [4, 50], [4, 50], [4, 0]], 6))
    .toBe('M0,100L0,52Q0,50 2,50L2,50Q4,50 4,48L4,0'))
  it('ребёнок ровно под родителями — прямая', () => expect(roundedPath([[10, 100], [10, 50], [10, 50], [10, 50], [10, 50], [10, 0]], 6))
    .toBe('M10,100L10,0'))
})
